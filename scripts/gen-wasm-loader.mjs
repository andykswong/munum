// Generates wasm/index.js: a portable loader for the munum core WebAssembly
// module. The module is inlined as base64 and instantiated behind a top-level
// await, so its raw linear `memory` and pointer-based exports are available
// synchronously to importers in Node, browsers, Vitest, and any bundler — with
// no reliance on WebAssembly-ESM integration or a bundler-specific asset loader.
//
// Run automatically by `npm run build` after wasm-opt. Reads the authoritative
// export names straight from the module's export section so the generated
// bindings can never drift from the compiled artifact.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const WASM_PATH = fileURLToPath(new URL('../wasm/munum.wasm', import.meta.url));
const OUT_PATH = fileURLToPath(new URL('../wasm/index.js', import.meta.url));

// Linker-emitted symbols that are not part of the public API.
const INTERNAL_EXPORTS = new Set(['__data_end', '__heap_base', '__indirect_function_table']);

/** Reads a LEB128 unsigned integer from `bytes` starting at `offset`. */
function readVarUint(bytes, offset) {
  let result = 0;
  let shift = 0;
  let pos = offset;
  for (;;) {
    const byte = bytes[pos++];
    result |= (byte & 0x7f) << shift;
    if ((byte & 0x80) === 0) break;
    shift += 7;
  }
  return [result >>> 0, pos];
}

/** Parses the export section of a core WebAssembly module and returns export names. */
function readExportNames(bytes) {
  // Skip the 8-byte header (magic + version).
  let offset = 8;
  const decoder = new TextDecoder();
  while (offset < bytes.length) {
    const sectionId = bytes[offset++];
    let sectionSize;
    [sectionSize, offset] = readVarUint(bytes, offset);
    if (sectionId !== 7) {
      // Not the export section (id 7) — skip its body.
      offset += sectionSize;
      continue;
    }
    const names = [];
    let count;
    [count, offset] = readVarUint(bytes, offset);
    for (let i = 0; i < count; i++) {
      let nameLen;
      [nameLen, offset] = readVarUint(bytes, offset);
      const name = decoder.decode(bytes.subarray(offset, offset + nameLen));
      offset += nameLen;
      // Skip export kind (1 byte) + index (varuint).
      offset += 1;
      [, offset] = readVarUint(bytes, offset);
      names.push(name);
    }
    return names;
  }
  throw new Error('no export section found in wasm module');
}

const wasm = readFileSync(WASM_PATH);
const allExports = readExportNames(wasm);

const publicExports = allExports.filter((name) => !INTERNAL_EXPORTS.has(name));
if (!publicExports.includes('memory')) {
  throw new Error('wasm module does not export `memory`');
}

// `memory` first, then the functions in a stable sorted order.
const names = ['memory', ...publicExports.filter((n) => n !== 'memory').sort()];

const base64 = wasm.toString('base64');

const source = `// AUTO-GENERATED by scripts/gen-wasm-loader.mjs — DO NOT EDIT.
//
// Portable loader for the munum core WebAssembly module. The module is inlined
// as base64 and instantiated behind a top-level await, exposing its raw linear
// \`memory\` and pointer-based exports synchronously to importers. Works in Node,
// browsers, and any bundler without WebAssembly-ESM integration or asset config.
import * as libmath from 'libmath';

const wasmBase64 =
  '${base64}';

function toBytes(base64) {
  if (typeof Buffer !== 'undefined') {
    return Buffer.from(base64, 'base64');
  }
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return bytes;
}

const { instance } = await WebAssembly.instantiate(toBytes(wasmBase64), { libmath });

export const {
  ${names.join(',\n  ')},
} = instance.exports;
`;

writeFileSync(OUT_PATH, source);
console.log(
  `gen-wasm-loader: wrote ${OUT_PATH} (${base64.length} base64 chars, ` +
    `${names.length - 1} functions + memory)`,
);
